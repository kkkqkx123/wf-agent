//! wf-cli-demo: runnable demos for every wf-agent CLI implementation.
//!
//! This crate is demo-only. It contains no product logic: each `examples/`
//! target showcases one CLI form — full TUI widgets (via `wf-tui`), the
//! shared headless surface (via `wf-cli-shared`), and the mini form — so
//! developers can inspect and run each implementation without touching
//! product crates.
