export type DangerLevel = 'readonly' | 'recoverable' | 'destructive' | 'history_rewrite';

export interface BindingItem {
	id: string;
	name: string;
	aliases: string[];
	hint: string;
	hidden: boolean;
	weight: number;
	danger: DangerLevel;
	params: string[];
	contexts: string[];
	legacyKey: string | null;
	nonPrintable: boolean;
	controlPriority: number;
}

type RawBinding = Omit<BindingItem, 'legacyKey' | 'nonPrintable' | 'controlPriority'>;

